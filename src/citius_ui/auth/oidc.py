"""OIDC configuration loading and Authorization Code with PKCE building blocks.

This module owns the non-network parts of the interactive login flow: loading
the non-secret configuration generated by the Citius Zitadel bootstrap, and
constructing the PKCE parameters and authorization URL. The token exchange,
refresh, and federated logout HTTP calls are performed by the FastAPI routes
against a live Zitadel and are configured from this model.
"""

from __future__ import annotations

import base64
import hashlib
import json
import secrets
import time
from dataclasses import dataclass, field, replace
from pathlib import Path
from urllib.parse import urlencode

import httpx
import jwt
from jwt import PyJWKClient

_DEFAULT_SCOPES = ("openid", "profile", "email", "offline_access")

# Reserved Zitadel scope asking for the caller's project role grants to be
# embedded as claims, so the UI can display the granted permissions.
_ZITADEL_ROLES_SCOPE = "urn:zitadel:iam:org:projects:roles"

# Claim keys Zitadel uses for project role grants: the plain form plus the
# project-scoped form `urn:zitadel:iam:org:project:<id>:roles`.
_ZITADEL_ROLES_CLAIM = "urn:zitadel:iam:org:project:roles"
_ZITADEL_ROLES_CLAIM_PREFIX = "urn:zitadel:iam:org:project:"
_ZITADEL_ROLES_CLAIM_SUFFIX = ":roles"

# Custom claims injected by the Citius Zitadel token action (see
# citius-server/bootstrap/zitadel: the action maps project-role grants and
# key-access metadata into the urn:citius namespace). The action runs on the
# pre-userinfo trigger, so these claims are guaranteed on the userinfo
# endpoint and appear in the ID token only when the app asserts userinfo.
_CITIUS_PERMISSIONS_CLAIM = "urn:citius:permissions"
_CITIUS_KEY_ALLOW_CLAIM = "urn:citius:allowed_key_patterns"
_CITIUS_KEY_DENY_CLAIM = "urn:citius:deny_key_patterns"

# Signing algorithms Zitadel advertises for ID tokens. Symmetric algorithms are
# deliberately excluded so a leaked shared secret can never forge an ID token.
_ALLOWED_ID_TOKEN_ALGS = (
    "EdDSA",
    "RS256",
    "RS384",
    "RS512",
    "ES256",
    "ES384",
    "ES512",
)


@dataclass(frozen=True, slots=True)
class OIDCConfig:
    """Non-secret OIDC relying-party configuration for the UI."""

    issuer: str
    client_id: str
    audience: str
    redirect_uri: str
    post_logout_redirect_uri: str
    enable_refresh_tokens: bool

    @property
    def authorization_endpoint(self) -> str:
        return f"{self.issuer.rstrip('/')}/oauth/v2/authorize"

    @property
    def token_endpoint(self) -> str:
        return f"{self.issuer.rstrip('/')}/oauth/v2/token"

    @property
    def end_session_endpoint(self) -> str:
        return f"{self.issuer.rstrip('/')}/oidc/v1/end_session"

    @property
    def jwks_uri(self) -> str:
        return f"{self.issuer.rstrip('/')}/oauth/v2/keys"

    @property
    def userinfo_endpoint(self) -> str:
        return f"{self.issuer.rstrip('/')}/oidc/v1/userinfo"


def load_oidc_config(path: Path | str) -> OIDCConfig:
    """Load the generated Zitadel UI auth configuration file."""
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    web_app = data.get("web_app")
    if not isinstance(web_app, dict):
        raise ValueError("OIDC config is missing the web_app section")
    redirect_uris = web_app.get("redirect_uris") or []
    logout_uris = web_app.get("post_logout_redirect_uris") or []
    if not redirect_uris:
        raise ValueError("OIDC config has no redirect_uris")
    if not logout_uris:
        raise ValueError("OIDC config has no post_logout_redirect_uris")
    issuer = str(data.get("issuer", "")).strip()
    client_id = str(web_app.get("client_id", "")).strip()
    if not issuer or not client_id:
        raise ValueError("OIDC config requires issuer and web_app.client_id")
    return OIDCConfig(
        issuer=issuer,
        client_id=client_id,
        audience=str(data.get("audience", "")).strip(),
        redirect_uri=str(redirect_uris[0]),
        post_logout_redirect_uri=str(logout_uris[0]),
        enable_refresh_tokens=bool(web_app.get("enable_refresh_tokens", False)),
    )


def _urlsafe(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode("ascii")


@dataclass(frozen=True, slots=True)
class PkceChallenge:
    """A PKCE verifier and its S256 challenge with CSRF state and nonce."""

    verifier: str
    challenge: str
    state: str
    nonce: str
    method: str = "S256"


def create_pkce_challenge() -> PkceChallenge:
    """Generate a PKCE verifier/challenge pair plus CSRF state and nonce."""
    verifier = _urlsafe(secrets.token_bytes(64))
    digest = hashlib.sha256(verifier.encode("ascii")).digest()
    return PkceChallenge(
        verifier=verifier,
        challenge=_urlsafe(digest),
        state=_urlsafe(secrets.token_bytes(24)),
        nonce=_urlsafe(secrets.token_bytes(24)),
    )


def authorization_url(
    config: OIDCConfig,
    pkce: PkceChallenge,
    *,
    scopes: tuple[str, ...] = _DEFAULT_SCOPES,
) -> str:
    """Build the Zitadel authorization URL for Authorization Code with PKCE.

    The configured ``audience`` is appended to the requested scopes. For Zitadel
    it is the reserved ``urn:zitadel:iam:org:project:id:<project>:aud`` value,
    which is what makes Zitadel embed the Citius project audience in the issued
    access token. Without it the token carries no Citius audience and the server
    rejects every RPC as UNAUTHENTICATED.
    """
    effective = scopes
    if not config.enable_refresh_tokens:
        effective = tuple(scope for scope in scopes if scope != "offline_access")
    if _ZITADEL_ROLES_SCOPE not in effective:
        effective = (*effective, _ZITADEL_ROLES_SCOPE)
    if config.audience and config.audience not in effective:
        effective = (*effective, config.audience)
    params = {
        "client_id": config.client_id,
        "response_type": "code",
        "scope": " ".join(effective),
        "redirect_uri": config.redirect_uri,
        "state": pkce.state,
        "nonce": pkce.nonce,
        "code_challenge": pkce.challenge,
        "code_challenge_method": pkce.method,
    }
    return f"{config.authorization_endpoint}?{urlencode(params)}"


class OIDCError(Exception):
    """Raised when the token exchange or refresh fails."""


@dataclass(frozen=True, slots=True)
class TokenSet:
    """Tokens returned by the OIDC token endpoint."""

    access_token: str
    refresh_token: str = ""
    id_token: str = ""
    expires_in: int | None = None

    @classmethod
    def from_response(cls, payload: object) -> TokenSet:
        if not isinstance(payload, dict):
            raise OIDCError("token response is not a JSON object")
        access_token = str(payload.get("access_token", ""))
        if not access_token:
            raise OIDCError("token response did not include an access_token")
        expires = payload.get("expires_in")
        return cls(
            access_token=access_token,
            refresh_token=str(payload.get("refresh_token", "")),
            id_token=str(payload.get("id_token", "")),
            expires_in=int(expires) if isinstance(expires, (int, float, str)) and expires != "" else None,
        )


def _json_body(response: httpx.Response) -> object:
    try:
        return response.json()
    except ValueError as exc:
        raise OIDCError("token endpoint returned a non-JSON response") from exc


def _error_detail(response: httpx.Response) -> str:
    """Extract the OAuth error/error_description from an error response body."""
    try:
        payload = response.json()
    except ValueError:
        return ""
    if not isinstance(payload, dict):
        return ""
    parts = [str(payload[key]) for key in ("error", "error_description") if payload.get(key)]
    return f" ({': '.join(parts)})" if parts else ""


async def exchange_code(
    client: httpx.AsyncClient,
    config: OIDCConfig,
    *,
    code: str,
    code_verifier: str,
) -> TokenSet:
    """Exchange an authorization code for tokens using PKCE (no client secret)."""
    try:
        response = await client.post(
            config.token_endpoint,
            data={
                "grant_type": "authorization_code",
                "code": code,
                "redirect_uri": config.redirect_uri,
                "client_id": config.client_id,
                "code_verifier": code_verifier,
            },
        )
    except httpx.HTTPError as exc:
        raise OIDCError(f"could not reach the token endpoint: {exc}") from exc
    if response.status_code != httpx.codes.OK:
        raise OIDCError(f"token exchange failed with status {response.status_code}{_error_detail(response)}")
    return TokenSet.from_response(_json_body(response))


async def refresh_tokens(
    client: httpx.AsyncClient,
    config: OIDCConfig,
    *,
    refresh_token: str,
) -> TokenSet:
    """Exchange a refresh token for a new token set."""
    try:
        response = await client.post(
            config.token_endpoint,
            data={
                "grant_type": "refresh_token",
                "refresh_token": refresh_token,
                "client_id": config.client_id,
            },
        )
    except httpx.HTTPError as exc:
        raise OIDCError(f"could not reach the token endpoint: {exc}") from exc
    if response.status_code != httpx.codes.OK:
        raise OIDCError(f"token refresh failed with status {response.status_code}{_error_detail(response)}")
    return TokenSet.from_response(_json_body(response))


def end_session_url(config: OIDCConfig, *, id_token: str = "") -> str:
    """Build the federated-logout URL for the Zitadel end-session endpoint."""
    params: dict[str, str] = {
        "client_id": config.client_id,
        "post_logout_redirect_uri": config.post_logout_redirect_uri,
    }
    if id_token:
        params["id_token_hint"] = id_token
    return f"{config.end_session_endpoint}?{urlencode(params)}"


@dataclass(frozen=True, slots=True)
class Identity:
    """Displayable identity derived from validated ID-token claims.

    Only non-sensitive claims are retained. Never carries the raw token.
    """

    subject: str
    display_name: str
    username: str = ""
    email: str = ""
    roles: frozenset[str] = frozenset()
    claims: dict[str, object] = field(default_factory=dict)


def refine_identity(identity: Identity, claims: dict[str, object]) -> Identity:
    """Recompute username/display_name/email from claims that may include userinfo.

    Zitadel only embeds profile claims (name, preferred_username, email) in the
    ID token when the application enables "user info inside ID token"; the
    common configuration returns them from the userinfo endpoint only. Callers
    merge userinfo claims onto the validated ID-token claims and pass the
    result here so the display name isn't left as the bare subject. The
    userinfo response's subject must match the validated identity's subject —
    a mismatch is ignored rather than trusted, since userinfo is fetched with
    the access token and is not itself signature-verified like the ID token.
    """
    if str(claims.get("sub", "")).strip() != identity.subject:
        return identity
    name = str(claims.get("name") or "").strip()
    preferred_username = str(claims.get("preferred_username") or "").strip()
    email = str(claims.get("email") or "").strip()
    # Only overwrite a field when the merged claims independently supply a
    # replacement; otherwise keep the identity's existing value rather than
    # falling back to another field's value (e.g. username) and clobbering it.
    username = preferred_username or email or identity.username
    display_name = name or preferred_username or identity.display_name
    return replace(identity, username=username, display_name=display_name, email=email or identity.email)


@dataclass(frozen=True, slots=True)
class AccessGrants:
    """Displayable permission and key-access grants from token claims."""

    permissions: frozenset[str] = frozenset()
    key_allow: tuple[str, ...] = ()
    key_deny: tuple[str, ...] = ()


def _string_items(value: object) -> tuple[str, ...]:
    if isinstance(value, (list, tuple)):
        return tuple(str(item).strip() for item in value if str(item).strip())
    return ()


def extract_grants(claims: dict[str, object]) -> AccessGrants:
    """Read the Citius permission and key-access claims from token claims.

    The Citius token action projects project-role grants into
    ``urn:citius:permissions`` and key-access metadata into the allow/deny
    pattern claims. When the custom permissions claim is absent (action not
    wired, or claims from a bare ID token), the standard Zitadel project-role
    claims are used as a fallback so the UI still shows granted roles.
    """
    permissions = frozenset(_string_items(claims.get(_CITIUS_PERMISSIONS_CLAIM)))
    if not permissions:
        permissions = extract_roles(claims)
    return AccessGrants(
        permissions=permissions,
        key_allow=_string_items(claims.get(_CITIUS_KEY_ALLOW_CLAIM)),
        key_deny=_string_items(claims.get(_CITIUS_KEY_DENY_CLAIM)),
    )


async def fetch_userinfo(
    client: httpx.AsyncClient,
    config: OIDCConfig,
    *,
    access_token: str,
) -> dict[str, object]:
    """Fetch userinfo claims for the access token from the issuer.

    The Citius token action runs on Zitadel's pre-userinfo trigger, so this is
    the authoritative source of the ``urn:citius:*`` claims for a hosted login.
    """
    try:
        response = await client.get(
            config.userinfo_endpoint,
            headers={"Authorization": f"Bearer {access_token}"},
        )
    except httpx.HTTPError as exc:
        raise OIDCError(f"could not reach the userinfo endpoint: {exc}") from exc
    if response.status_code != httpx.codes.OK:
        raise OIDCError(f"userinfo request failed with status {response.status_code}{_error_detail(response)}")
    try:
        payload = response.json()
    except ValueError as exc:
        raise OIDCError("userinfo endpoint returned a non-JSON response") from exc
    if not isinstance(payload, dict):
        raise OIDCError("userinfo response is not a JSON object")
    return payload


def extract_roles(claims: dict[str, object]) -> frozenset[str]:
    """Collect Zitadel project role names from ID-token claims.

    Zitadel embeds granted roles as ``urn:zitadel:iam:org:project:roles`` and/or
    ``urn:zitadel:iam:org:project:<id>:roles``, each mapping role name to the
    granting organizations. Only the role names are retained.
    """
    roles: set[str] = set()
    for key, value in claims.items():
        is_roles_claim = key == _ZITADEL_ROLES_CLAIM or (
            key.startswith(_ZITADEL_ROLES_CLAIM_PREFIX) and key.endswith(_ZITADEL_ROLES_CLAIM_SUFFIX)
        )
        if not is_roles_claim:
            continue
        if isinstance(value, dict):
            roles.update(str(role) for role in value)
        elif isinstance(value, (list, tuple)):
            roles.update(str(role) for role in value)
    return frozenset(roles)


class _JWKSCache:
    """Process-wide cache of PyJWKClient instances keyed by JWKS URI.

    PyJWKClient caches signing keys internally and refreshes on cache miss, so
    Zitadel key rotation is handled transparently. A CA file may be supplied so
    the JWKS fetch trusts the local mkcert root during development.
    """

    def __init__(self) -> None:
        self._clients: dict[tuple[str, str], PyJWKClient] = {}

    def get(self, jwks_uri: str, *, ca_cert: str | None = None) -> PyJWKClient:
        key = (jwks_uri, ca_cert or "")
        client = self._clients.get(key)
        if client is None:
            ssl_context = None
            if ca_cert:
                import ssl

                ssl_context = ssl.create_default_context(cafile=ca_cert)
            client = PyJWKClient(jwks_uri, cache_keys=True, ssl_context=ssl_context)
            self._clients[key] = client
        return client


_JWKS_CACHE = _JWKSCache()


def validate_id_token(
    id_token: str,
    config: OIDCConfig,
    *,
    nonce: str,
    ca_cert: str | None = None,
    leeway: int = 30,
    now: int | None = None,
) -> Identity:
    """Verify an ID token's signature and issuer/audience/nonce/expiry claims.

    The signature is verified against the issuer's JWKS. The issuer must match
    the configured issuer exactly, the audience must include the web-app client
    id, the token must be unexpired, and the nonce must equal the one bound to
    this login attempt. Returns the displayable identity on success.
    """
    if not id_token:
        raise OIDCError("no id_token returned; cannot validate identity")
    jwks = _JWKS_CACHE.get(config.jwks_uri, ca_cert=ca_cert)
    try:
        signing_key = jwks.get_signing_key_from_jwt(id_token)
    except Exception as exc:  # PyJWK raises a variety of key-resolution errors.
        raise OIDCError(f"could not resolve ID-token signing key: {exc}") from exc
    try:
        claims = jwt.decode(
            id_token,
            signing_key.key,
            algorithms=list(_ALLOWED_ID_TOKEN_ALGS),
            audience=config.client_id,
            issuer=config.issuer,
            leeway=leeway,
            options={"require": ["exp", "iat", "iss", "aud", "sub"]},
        )
    except jwt.InvalidTokenError as exc:
        raise OIDCError(f"invalid ID token: {exc}") from exc

    token_nonce = claims.get("nonce")
    if not nonce or token_nonce != nonce:
        raise OIDCError("ID-token nonce does not match the login request")

    # Redundant explicit expiry check independent of PyJWT leeway handling.
    moment = int(time.time()) if now is None else now
    exp = claims.get("exp")
    if isinstance(exp, (int, float)) and moment - leeway >= int(exp):
        raise OIDCError("ID token is expired")

    subject = str(claims.get("sub", "")).strip()
    if not subject:
        raise OIDCError("ID token has no subject claim")
    username = str(claims.get("preferred_username") or claims.get("email") or "").strip()
    display_name = str(claims.get("name") or claims.get("preferred_username") or username or subject).strip()
    return Identity(
        subject=subject,
        display_name=display_name,
        username=username,
        email=str(claims.get("email", "")).strip(),
        roles=extract_roles(claims),
        claims=claims,
    )
