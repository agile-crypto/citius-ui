"""OIDC configuration loading and Authorization Code with PKCE building blocks.

This module owns the non-network parts of the interactive login flow: loading
the non-secret configuration generated by the Citius Zitadel bootstrap, and
constructing the PKCE parameters and authorization URL. The token exchange,
refresh, and federated logout HTTP calls are performed by the FastAPI routes
against a live Zitadel and are configured from this model.
"""

from __future__ import annotations

import base64
import hashlib
import json
import secrets
import time
from dataclasses import dataclass, field
from pathlib import Path
from urllib.parse import urlencode

import httpx
import jwt
from jwt import PyJWKClient

_DEFAULT_SCOPES = ("openid", "profile", "email", "offline_access")

# Signing algorithms Zitadel advertises for ID tokens. Symmetric algorithms are
# deliberately excluded so a leaked shared secret can never forge an ID token.
_ALLOWED_ID_TOKEN_ALGS = (
    "EdDSA",
    "RS256",
    "RS384",
    "RS512",
    "ES256",
    "ES384",
    "ES512",
)


@dataclass(frozen=True, slots=True)
class OIDCConfig:
    """Non-secret OIDC relying-party configuration for the UI."""

    issuer: str
    client_id: str
    audience: str
    redirect_uri: str
    post_logout_redirect_uri: str
    enable_refresh_tokens: bool

    @property
    def authorization_endpoint(self) -> str:
        return f"{self.issuer.rstrip('/')}/oauth/v2/authorize"

    @property
    def token_endpoint(self) -> str:
        return f"{self.issuer.rstrip('/')}/oauth/v2/token"

    @property
    def end_session_endpoint(self) -> str:
        return f"{self.issuer.rstrip('/')}/oidc/v1/end_session"

    @property
    def jwks_uri(self) -> str:
        return f"{self.issuer.rstrip('/')}/oauth/v2/keys"


def load_oidc_config(path: Path | str) -> OIDCConfig:
    """Load the generated Zitadel UI auth configuration file."""
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    web_app = data.get("web_app")
    if not isinstance(web_app, dict):
        raise ValueError("OIDC config is missing the web_app section")
    redirect_uris = web_app.get("redirect_uris") or []
    logout_uris = web_app.get("post_logout_redirect_uris") or []
    if not redirect_uris:
        raise ValueError("OIDC config has no redirect_uris")
    if not logout_uris:
        raise ValueError("OIDC config has no post_logout_redirect_uris")
    issuer = str(data.get("issuer", "")).strip()
    client_id = str(web_app.get("client_id", "")).strip()
    if not issuer or not client_id:
        raise ValueError("OIDC config requires issuer and web_app.client_id")
    return OIDCConfig(
        issuer=issuer,
        client_id=client_id,
        audience=str(data.get("audience", "")).strip(),
        redirect_uri=str(redirect_uris[0]),
        post_logout_redirect_uri=str(logout_uris[0]),
        enable_refresh_tokens=bool(web_app.get("enable_refresh_tokens", False)),
    )


def _urlsafe(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode("ascii")


@dataclass(frozen=True, slots=True)
class PkceChallenge:
    """A PKCE verifier and its S256 challenge with CSRF state and nonce."""

    verifier: str
    challenge: str
    state: str
    nonce: str
    method: str = "S256"


def create_pkce_challenge() -> PkceChallenge:
    """Generate a PKCE verifier/challenge pair plus CSRF state and nonce."""
    verifier = _urlsafe(secrets.token_bytes(64))
    digest = hashlib.sha256(verifier.encode("ascii")).digest()
    return PkceChallenge(
        verifier=verifier,
        challenge=_urlsafe(digest),
        state=_urlsafe(secrets.token_bytes(24)),
        nonce=_urlsafe(secrets.token_bytes(24)),
    )


def authorization_url(
    config: OIDCConfig,
    pkce: PkceChallenge,
    *,
    scopes: tuple[str, ...] = _DEFAULT_SCOPES,
) -> str:
    """Build the Zitadel authorization URL for Authorization Code with PKCE."""
    effective = scopes
    if not config.enable_refresh_tokens:
        effective = tuple(scope for scope in scopes if scope != "offline_access")
    params = {
        "client_id": config.client_id,
        "response_type": "code",
        "scope": " ".join(effective),
        "redirect_uri": config.redirect_uri,
        "state": pkce.state,
        "nonce": pkce.nonce,
        "code_challenge": pkce.challenge,
        "code_challenge_method": pkce.method,
    }
    return f"{config.authorization_endpoint}?{urlencode(params)}"


class OIDCError(Exception):
    """Raised when the token exchange or refresh fails."""


@dataclass(frozen=True, slots=True)
class TokenSet:
    """Tokens returned by the OIDC token endpoint."""

    access_token: str
    refresh_token: str = ""
    id_token: str = ""
    expires_in: int | None = None

    @classmethod
    def from_response(cls, payload: dict[str, object]) -> TokenSet:
        access_token = str(payload.get("access_token", ""))
        if not access_token:
            raise OIDCError("token response did not include an access_token")
        expires = payload.get("expires_in")
        return cls(
            access_token=access_token,
            refresh_token=str(payload.get("refresh_token", "")),
            id_token=str(payload.get("id_token", "")),
            expires_in=int(expires) if isinstance(expires, (int, float, str)) and expires != "" else None,
        )


async def exchange_code(
    client: httpx.AsyncClient,
    config: OIDCConfig,
    *,
    code: str,
    code_verifier: str,
) -> TokenSet:
    """Exchange an authorization code for tokens using PKCE (no client secret)."""
    try:
        response = await client.post(
            config.token_endpoint,
            data={
                "grant_type": "authorization_code",
                "code": code,
                "redirect_uri": config.redirect_uri,
                "client_id": config.client_id,
                "code_verifier": code_verifier,
            },
        )
    except httpx.TransportError as exc:
        raise OIDCError(f"could not reach the token endpoint: {exc}") from exc
    if response.status_code != httpx.codes.OK:
        raise OIDCError(f"token exchange failed with status {response.status_code}")
    return TokenSet.from_response(response.json())


async def refresh_tokens(
    client: httpx.AsyncClient,
    config: OIDCConfig,
    *,
    refresh_token: str,
) -> TokenSet:
    """Exchange a refresh token for a new token set."""
    try:
        response = await client.post(
            config.token_endpoint,
            data={
                "grant_type": "refresh_token",
                "refresh_token": refresh_token,
                "client_id": config.client_id,
            },
        )
    except httpx.TransportError as exc:
        raise OIDCError(f"could not reach the token endpoint: {exc}") from exc
    if response.status_code != httpx.codes.OK:
        raise OIDCError(f"token refresh failed with status {response.status_code}")
    return TokenSet.from_response(response.json())


def end_session_url(config: OIDCConfig, *, id_token: str = "") -> str:
    """Build the federated-logout URL for the Zitadel end-session endpoint."""
    params: dict[str, str] = {
        "client_id": config.client_id,
        "post_logout_redirect_uri": config.post_logout_redirect_uri,
    }
    if id_token:
        params["id_token_hint"] = id_token
    return f"{config.end_session_endpoint}?{urlencode(params)}"


@dataclass(frozen=True, slots=True)
class Identity:
    """Displayable identity derived from validated ID-token claims.

    Only non-sensitive claims are retained. Never carries the raw token.
    """

    subject: str
    display_name: str
    username: str = ""
    email: str = ""
    claims: dict[str, object] = field(default_factory=dict)


class _JWKSCache:
    """Process-wide cache of PyJWKClient instances keyed by JWKS URI.

    PyJWKClient caches signing keys internally and refreshes on cache miss, so
    Zitadel key rotation is handled transparently. A CA file may be supplied so
    the JWKS fetch trusts the local mkcert root during development.
    """

    def __init__(self) -> None:
        self._clients: dict[tuple[str, str], PyJWKClient] = {}

    def get(self, jwks_uri: str, *, ca_cert: str | None = None) -> PyJWKClient:
        key = (jwks_uri, ca_cert or "")
        client = self._clients.get(key)
        if client is None:
            ssl_context = None
            if ca_cert:
                import ssl

                ssl_context = ssl.create_default_context(cafile=ca_cert)
            client = PyJWKClient(jwks_uri, cache_keys=True, ssl_context=ssl_context)
            self._clients[key] = client
        return client


_JWKS_CACHE = _JWKSCache()


def validate_id_token(
    id_token: str,
    config: OIDCConfig,
    *,
    nonce: str,
    ca_cert: str | None = None,
    leeway: int = 30,
    now: int | None = None,
) -> Identity:
    """Verify an ID token's signature and issuer/audience/nonce/expiry claims.

    The signature is verified against the issuer's JWKS. The issuer must match
    the configured issuer exactly, the audience must include the web-app client
    id, the token must be unexpired, and the nonce must equal the one bound to
    this login attempt. Returns the displayable identity on success.
    """
    if not id_token:
        raise OIDCError("no id_token returned; cannot validate identity")
    jwks = _JWKS_CACHE.get(config.jwks_uri, ca_cert=ca_cert)
    try:
        signing_key = jwks.get_signing_key_from_jwt(id_token)
    except Exception as exc:  # PyJWK raises a variety of key-resolution errors.
        raise OIDCError(f"could not resolve ID-token signing key: {exc}") from exc
    try:
        claims = jwt.decode(
            id_token,
            signing_key.key,
            algorithms=list(_ALLOWED_ID_TOKEN_ALGS),
            audience=config.client_id,
            issuer=config.issuer,
            leeway=leeway,
            options={"require": ["exp", "iat", "iss", "aud", "sub"]},
        )
    except jwt.InvalidTokenError as exc:
        raise OIDCError(f"invalid ID token: {exc}") from exc

    token_nonce = claims.get("nonce")
    if not nonce or token_nonce != nonce:
        raise OIDCError("ID-token nonce does not match the login request")

    # Redundant explicit expiry check independent of PyJWT leeway handling.
    moment = int(time.time()) if now is None else now
    exp = claims.get("exp")
    if isinstance(exp, (int, float)) and moment - leeway >= int(exp):
        raise OIDCError("ID token is expired")

    subject = str(claims.get("sub", "")).strip()
    if not subject:
        raise OIDCError("ID token has no subject claim")
    username = str(claims.get("preferred_username") or claims.get("email") or "").strip()
    display_name = str(claims.get("name") or claims.get("preferred_username") or username or subject).strip()
    return Identity(
        subject=subject,
        display_name=display_name,
        username=username,
        email=str(claims.get("email", "")).strip(),
        claims=claims,
    )
